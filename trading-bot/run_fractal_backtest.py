#!/usr/bin/env python3
"""
Backtest for TTrades Fractal Model Strategy

IMPORTANT DATA PROVENANCE NOTICE:
- This backtest uses SYNTHETIC data generated by the data_handler module
- Synthetic data uses a mean-reverting Ornstein-Uhlenbeck process
- Base price ~18000 (approximate NQ price)
- This is NOT real market data from any exchange or data provider
- Results should be treated as indicative only

Walk-forward testing approach:
- In-sample: First 70% of data for parameter validation
- Out-of-sample: Last 30% for unbiased performance measurement
"""
import sys
import json
from datetime import datetime
from pathlib import Path

from loguru import logger

from src.data.data_handler import DataHandler
from src.backtest.engine import BacktestEngine, BacktestResult
from src.backtest.metrics import generate_report
from src.strategies.fractal_model import FractalModelStrategy, FractalModelWithFVGStrategy

# Configure logging
logger.remove()
logger.add(sys.stdout, level="INFO", format="{time:HH:mm:ss} | {level} | {message}")

def run_walk_forward_test(
    data_handler: DataHandler,
    engine: BacktestEngine,
    strategy,
    full_data,
    in_sample_ratio: float = 0.7
):
    """
    Run walk-forward test with in-sample and out-of-sample periods
    
    This is more honest than optimizing on the full dataset.
    """
    split_idx = int(len(full_data) * in_sample_ratio)
    
    in_sample_data = full_data.iloc[:split_idx]
    out_of_sample_data = full_data.iloc[split_idx:]
    
    logger.info(f"In-sample: {len(in_sample_data)} bars ({in_sample_data.index[0]} to {in_sample_data.index[-1]})")
    logger.info(f"Out-of-sample: {len(out_of_sample_data)} bars ({out_of_sample_data.index[0]} to {out_of_sample_data.index[-1]})")
    
    # Run on in-sample (for reference)
    in_sample_result = engine.run(in_sample_data, strategy, verbose=False)
    
    # Run on out-of-sample (the real test)
    engine._reset()  # Reset engine state
    out_of_sample_result = engine.run(out_of_sample_data, strategy, verbose=False)
    
    return in_sample_result, out_of_sample_result


def main():
    print("\n" + "="*80)
    print("TTRADES FRACTAL MODEL BACKTEST")
    print("="*80)
    print("\nDATA PROVENANCE:")
    print("  Source: SYNTHETIC (generated by data_handler.py)")
    print("  Process: Mean-reverting Ornstein-Uhlenbeck")
    print("  Base Price: ~18000 (approximate NQ)")
    print("  NOT REAL MARKET DATA")
    print("="*80 + "\n")
    
    # Configuration
    START_DATE = "2024-06-01"
    END_DATE = "2024-12-31"
    INITIAL_CAPITAL = 25000.0
    DATA_INTERVAL = "5m"
    
    # Setup
    data_handler = DataHandler()
    
    logger.info(f"Generating synthetic data from {START_DATE} to {END_DATE}")
    data = data_handler.get_data(START_DATE, END_DATE, DATA_INTERVAL)
    data = data_handler.add_indicators(data)
    
    print(f"\nData Summary:")
    print(f"  Bars: {len(data)}")
    print(f"  Period: {data.index[0]} to {data.index[-1]}")
    print(f"  Source: SYNTHETIC (mean-reverting process)")
    print(f"  Interval: {DATA_INTERVAL}")
    
    # Setup backtest engine
    engine = BacktestEngine(
        initial_capital=INITIAL_CAPITAL,
        commission_per_contract=0.50,
        slippage_ticks=1.0,
        max_position_size=3,
        margin_per_contract=500.0
    )
    
    # Test strategies with varying parameters
    # Note: Relaxed parameters to generate more signals on synthetic data
    strategies = [
        # Strict version (as per TTrades)
        FractalModelStrategy(
            htf_bias_period=50,
            swing_strength=3,
            cisd_threshold=0.6,
            target_rr=2.0
        ),
        # Relaxed version (for more signals on synthetic data)
        FractalModelStrategy(
            htf_bias_period=20,
            swing_strength=2,
            cisd_threshold=0.3,
            target_rr=2.0
        ),
        # Very relaxed (to stress test on synthetic)
        FractalModelStrategy(
            htf_bias_period=10,
            swing_strength=1,
            cisd_threshold=0.2,
            target_rr=1.5
        ),
    ]
    
    results = []
    
    for strategy in strategies:
        print(f"\n{'='*60}")
        print(f"Testing: {strategy.name}")
        print(f"{'='*60}")
        
        # Walk-forward test
        in_sample, out_of_sample = run_walk_forward_test(
            data_handler, engine, strategy, data, in_sample_ratio=0.7
        )
        
        results.append({
            "strategy": strategy.name,
            "parameters": strategy.parameters,
            "in_sample": in_sample,
            "out_of_sample": out_of_sample
        })
        
        # Print results
        print(f"\nIN-SAMPLE Results (training period - DO NOT TRUST):")
        print(f"  Return: {in_sample.total_return_pct:.2f}%")
        print(f"  Sharpe: {in_sample.metrics.sharpe_ratio:.2f}")
        print(f"  Max DD: {in_sample.metrics.max_drawdown_pct:.2f}%")
        print(f"  Trades: {in_sample.metrics.total_trades}")
        print(f"  Win Rate: {in_sample.metrics.win_rate:.1f}%")
        
        print(f"\nOUT-OF-SAMPLE Results (unbiased test):")
        print(f"  Return: {out_of_sample.total_return_pct:.2f}%")
        print(f"  Sharpe: {out_of_sample.metrics.sharpe_ratio:.2f}")
        print(f"  Max DD: {out_of_sample.metrics.max_drawdown_pct:.2f}%")
        print(f"  Trades: {out_of_sample.metrics.total_trades}")
        print(f"  Win Rate: {out_of_sample.metrics.win_rate:.1f}%")
        print(f"  Profit Factor: {out_of_sample.metrics.profit_factor:.2f}")
        print(f"  Expectancy: ${out_of_sample.metrics.expectancy:.2f}")
    
    # Summary
    print("\n" + "="*80)
    print("SUMMARY - OUT-OF-SAMPLE RESULTS ONLY")
    print("="*80)
    print(f"{'Strategy':<30} {'Return %':>10} {'Sharpe':>8} {'MaxDD %':>10} {'Trades':>8} {'Win%':>8}")
    print("-"*80)
    
    for r in results:
        oos = r["out_of_sample"]
        m = oos.metrics
        print(f"{r['strategy']:<30} {oos.total_return_pct:>10.2f} {m.sharpe_ratio:>8.2f} "
              f"{m.max_drawdown_pct:>10.2f} {m.total_trades:>8} {m.win_rate:>8.1f}")
    
    print("-"*80)
    print("\nIMPORTANT: These results are from SYNTHETIC data.")
    print("Real market performance will differ significantly.")
    print("="*80)
    
    # Save results
    output_dir = Path("results")
    output_dir.mkdir(exist_ok=True)
    
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    
    results_json = []
    for r in results:
        oos = r["out_of_sample"]
        m = oos.metrics
        results_json.append({
            "strategy": r["strategy"],
            "parameters": r["parameters"],
            "data_source": "SYNTHETIC (mean-reverting O-U process)",
            "data_period": f"{START_DATE} to {END_DATE}",
            "data_interval": DATA_INTERVAL,
            "test_type": "walk_forward",
            "in_sample_ratio": 0.7,
            "out_of_sample_metrics": {
                "total_return_pct": float(oos.total_return_pct),
                "sharpe_ratio": float(m.sharpe_ratio),
                "max_drawdown_pct": float(m.max_drawdown_pct),
                "total_trades": int(m.total_trades),
                "win_rate": float(m.win_rate),
                "profit_factor": float(m.profit_factor),
                "expectancy": float(m.expectancy)
            }
        })
    
    json_path = output_dir / f"fractal_backtest_{timestamp}.json"
    with open(json_path, 'w') as f:
        json.dump(results_json, f, indent=2)
    
    print(f"\nResults saved to {json_path}")
    
    return results


if __name__ == "__main__":
    main()
